#!/usr/bin/env python3
"""Build miniapp/app.bundle.js + miniapp/app.bundle.css from the source files, in page order.

The Mini App used to load 22 scripts + 6 stylesheets (+1 inline block) one by one. They are
concatenated here in exactly the same order, so the cascade and the script execution order do not
change. Every source script is a single IIFE (tests/test_bundle.py checks that), and each one is
wrapped in its own try/catch, so one script throwing still lets the others run, as before.

Usage: python scripts/build_miniapp.py            (writes the bundles)
       python scripts/build_miniapp.py --check    (exit 1 if the bundles are stale)
"""
from __future__ import annotations

import sys
from pathlib import Path

MINI = Path(__file__).resolve().parent.parent / "miniapp"

CSS = [
    "styles.css", "home-fix.css", "home-inline.css", "theme-emerald.css",
    "status-badge.css", "hours.css", "area-filter.css", "upgrades.css", "place-pick.css", "coupons.css", "me-layout.css",
]
JS = [
    "cover.js", "net-cache.js", "resilience.js", "app.js", "home-ui.js", "hours-picker.js",
    "publish-ui.js", "me-listings.js", "detail-fix.js", "detail-kit.js", "role-nav.js", "fav.js",
    "share.js", "keyboard-fix.js", "deep-open.js", "detail-xhs.js", "review-back.js", "review-kit.js",
    "detail-guard.js", "swipe-back.js", "me-polish.js", "admin-go.js", "role-gate.js", "place-pick.js", "coupons.js", "me-layout.js",
]
HEAD = "/* GENERATED by scripts/build_miniapp.py from the miniapp source files. Do not edit. */\n"


def build_css() -> str:
    parts = [HEAD]
    for f in CSS:
        parts.append(f"/* ---- {f} ---- */\n{(MINI / f).read_text('utf-8').rstrip()}\n")
    return "".join(parts)


def build_js() -> str:
    parts = [HEAD]
    for f in JS:
        src = (MINI / f).read_text("utf-8").rstrip()
        parts.append(
            f"/* ---- {f} ---- */\ntry {{\n{src}\n;}} catch (e) {{ try {{ console.error(\"{f}\", e); "
            f"if (window.__yycjReport) window.__yycjReport({{ ev: \"js_error\", msg: String((e && e.message) || e), src: \"{f}\" }}); }} catch (x) {{}} }}\n"
        )
    return "".join(parts)


def main() -> int:
    out = {MINI / "app.bundle.css": build_css(), MINI / "app.bundle.js": build_js()}
    if "--check" in sys.argv:
        stale = [p.name for p, s in out.items() if not p.exists() or p.read_text("utf-8") != s]
        if stale:
            print("stale:", ", ".join(stale), "- run python scripts/build_miniapp.py")
            return 1
        return 0
    for p, s in out.items():
        p.write_text(s, "utf-8")
        print(f"wrote {p.relative_to(MINI.parent)} ({len(s.encode())} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
